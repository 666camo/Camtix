-- Drop existing tables if they exist
DROP TABLE IF EXISTS public.payments CASCADE;
DROP TABLE IF EXISTS public.bookings CASCADE;
DROP TABLE IF EXISTS public.payment_methods CASCADE;

-- ----------------------------------------------------------
-- Table: payment_methods
-- ----------------------------------------------------------
CREATE TABLE public.payment_methods (
    id_payment_method BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method_name VARCHAR(255),
    provider VARCHAR(255),
    account_number VARCHAR(255),
    account_name VARCHAR(255),
    qr_image TEXT,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE public.payment_methods OWNER TO postgres;

-- ----------------------------------------------------------
-- Table: bookings
-- ----------------------------------------------------------
CREATE TABLE public.bookings (
    id_booking BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_code VARCHAR(255) NOT NULL UNIQUE,
    user_id BIGINT,
    event_id BIGINT,
    ticket_id BIGINT,
    number_of_ticket INTEGER,
    total_price NUMERIC(38,2),
    booking_status VARCHAR(255),
    booking_date TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    expired_at TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE public.bookings OWNER TO postgres;

-- ----------------------------------------------------------
-- Table: payments
-- ----------------------------------------------------------
CREATE TABLE public.payments (
    id_payment BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT UNIQUE REFERENCES public.bookings(id_booking) ON DELETE CASCADE,
    payment_method_id BIGINT REFERENCES public.payment_methods(id_payment_method),
    total_payment NUMERIC(38,2),
    payment_status VARCHAR(255),
    payment_proof TEXT,
    payment_date TIMESTAMP(6) WITHOUT TIME ZONE,
    verified_at TIMESTAMP(6) WITHOUT TIME ZONE,
    admin_note VARCHAR(255),
    snap_token TEXT,
    midtrans_order_id VARCHAR(255),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE public.payments OWNER TO postgres;

