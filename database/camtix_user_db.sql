-- ----------------------------------------------------------
-- Table: users
-- ----------------------------------------------------------
CREATE TABLE public.users (
    id_user BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(255),
    last_name VARCHAR(255),
    age INTEGER,
    address VARCHAR(255),
    phone VARCHAR(255),
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255),
    role VARCHAR(255),
    is_verified BOOLEAN DEFAULT TRUE,
    is_banned BOOLEAN DEFAULT FALSE,
    reset_password_token VARCHAR(255),
    reset_password_token_expired_at TIMESTAMP(6) WITHOUT TIME ZONE,
    refresh_token VARCHAR(255),
    refresh_token_expired_at TIMESTAMP(6) WITHOUT TIME ZONE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE
);

ALTER TABLE public.users OWNER TO postgres;

-- ----------------------------------------------------------
-- Table: visitors
-- ----------------------------------------------------------
CREATE TABLE public.visitors (
    id_visitor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    activity VARCHAR(255),
    visit_date TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE public.visitors OWNER TO postgres;

-- ----------------------------------------------------------
-- Table: otp_verifications
-- ----------------------------------------------------------
CREATE TABLE public.otp_verifications (
    id_otp BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255),
    otp_code VARCHAR(255),
    expired_at TIMESTAMP(6) WITHOUT TIME ZONE,
    is_used BOOLEAN DEFAULT FALSE
);

ALTER TABLE public.otp_verifications OWNER TO postgres;

